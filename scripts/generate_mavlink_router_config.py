"""Generate a safe MAVLink Router fan-out config for a real vehicle link.

The generated topology gives the companion computer one vehicle-side UART and
two consumer-side UDP outputs: one for the normal GCS and one for the
non-commanding UTM connector. The output is explicit so an operator can review
it before installing it as the router configuration.
"""

from __future__ import annotations

import argparse
import ipaddress
from pathlib import Path
from typing import Sequence


def _endpoint_address(value: str, label: str) -> str:
    """Accept an IP or hostname while rejecting config-file injection."""

    value = value.strip()
    if not value or any(character in value for character in "\r\n=;"):
        raise ValueError(f"{label} must be a non-empty IP address or hostname")
    try:
        address = ipaddress.ip_address(value)
    except ValueError:
        if any(character.isspace() for character in value):
            raise ValueError(f"{label} must not contain whitespace")
        return value
    if address.version == 6:
        return f"[{address}]"
    return str(address)


def _port(value: int, label: str) -> int:
    if not 1 <= value <= 65535:
        raise ValueError(f"{label} must be between 1 and 65535")
    return value


def render_config(
    *,
    serial_device: str,
    baud: int = 57600,
    gcs_address: str = "127.0.0.1",
    gcs_port: int = 14550,
    connector_address: str = "127.0.0.1",
    connector_port: int = 14551,
) -> str:
    """Render a UART-backed router config without writing to disk."""

    serial_device = serial_device.strip()
    if not serial_device or any(character in serial_device for character in "\r\n="):
        raise ValueError("serial_device must be a non-empty device path")
    if baud <= 0:
        raise ValueError("baud must be a positive integer")
    gcs_address = _endpoint_address(gcs_address, "gcs_address")
    connector_address = _endpoint_address(connector_address, "connector_address")
    gcs_port = _port(gcs_port, "gcs_port")
    connector_port = _port(connector_port, "connector_port")
    if gcs_port == connector_port and gcs_address == connector_address:
        raise ValueError("GCS and connector endpoints must be different")

    return f"""# Generated by utm-adapter/scripts/generate_mavlink_router_config.py
# Review the addresses and install this file on the companion computer that
# owns the vehicle link. The UTM connector remains a non-commanding consumer.

[General]
TcpServerPort = 5760
ReportStats = false

[UartEndpoint vehicle_link]
Device = {serial_device}
Baud = {baud}

[UdpEndpoint qgroundcontrol]
Mode = Normal
Address = {gcs_address}
Port = {gcs_port}

[UdpEndpoint utm_connector]
Mode = Normal
Address = {connector_address}
Port = {connector_port}
"""


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--serial-device", required=True, help="vehicle UART, for example /dev/ttyUSB0 or COM3")
    parser.add_argument("--baud", type=int, default=57600)
    parser.add_argument("--gcs-address", default="127.0.0.1", help="GCS host/IP reachable from the companion computer")
    parser.add_argument("--gcs-port", type=int, default=14550)
    parser.add_argument("--connector-address", default="127.0.0.1", help="connector host/IP reachable from the companion computer")
    parser.add_argument("--connector-port", type=int, default=14551)
    parser.add_argument("--output", type=Path, help="write to this file; without it, print the config for review")
    parser.add_argument("--force", action="store_true", help="allow replacing an existing output file")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        rendered = render_config(
            serial_device=args.serial_device,
            baud=args.baud,
            gcs_address=args.gcs_address,
            gcs_port=args.gcs_port,
            connector_address=args.connector_address,
            connector_port=args.connector_port,
        )
        if args.output is None:
            print(rendered, end="")
            return 0
        output = args.output.expanduser()
        if output.exists() and not args.force:
            raise ValueError(f"output already exists: {output} (use --force to replace it)")
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(rendered, encoding="utf-8")
    except (OSError, ValueError) as exc:
        print(f"[error] {exc}")
        return 1
    print(f"[ok] wrote MAVLink Router config: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
